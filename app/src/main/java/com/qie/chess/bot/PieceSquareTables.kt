        -10, 0, 5, 0, 0, 0, 0, -10,
        -20, -10, -10, -5, -5, -10, -10, -20
    )

    private val KING_MIDDLEGAME = intArrayOf(
        20, 30, 10, 0, 0, 10, 30, 20,
        20, 20, 0, 0, 0, 0, 20, 20,
        -10, -20, -20, -20, -20, -20, -20, -10,
        -20, -30, -30, -40, -40, -30, -30, -20,
        -30, -40, -40, -50, -50, -40, -40, -30,
        -30, -40, -40, -50, -50, -40, -40, -30,
        -30, -40, -40, -50, -50, -40, -40, -30,
        -30, -40, -40, -50, -50, -40, -40, -30
    )

    fun valueFor(type: PieceType, file: Int, rank: Int, isWhite: Boolean): Int {
        // Tables are laid out rank 8 (index 0) down to rank 1 (index 7);
        // flip for white since our rank 0 == chess rank 1.
        val row = if (isWhite) 7 - rank else rank
        val index = row * 8 + file
        return when (type) {
            PieceType.PAWN -> PAWN[index]
            PieceType.KNIGHT -> KNIGHT[index]
            PieceType.BISHOP -> BISHOP[index]
            PieceType.ROOK -> ROOK[index]
            PieceType.QUEEN -> QUEEN[index]
            PieceType.KING -> KING_MIDDLEGAME[index]
        }
    }
}
